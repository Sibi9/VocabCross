needed = set()
for c in chars:
    if c in forms:
        needed.update(forms[c][:4])
needed.update([0xFEF5, 0xFEF6, 0xFEF7, 0xFEF8, 0xFEF9, 0xFEFA, 0xFEFB, 0xFEFC])
needed.update(ord(c) for c in chars)

for f in ['assets/fonts/Cairo.ttf', 'assets/fonts/tahoma.ttf', 'assets/fonts/segoeui.ttf']:
    t = TTFont(f)
    cmap = t.getBestCmap()
    missing = sorted(c for c in needed if c not in cmap)
    print(f, 'needed', len(needed), 'missing', len(missing), [hex(c) for c in missing[:30]])

